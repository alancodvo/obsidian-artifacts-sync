import esbuild from "esbuild";
import process from "node:process";

// Node built-ins that stay external (desktop loads them lazily through require). Listed by hand so
// the bundle depends on nothing outside esbuild to decide what is external.
const builtinModules = ["fs", "path", "http", "https", "url", "querystring", "crypto", "zlib", "stream", "os", "child_process", "util", "net", "tls", "assert", "module", "process"];

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";
const POLYFILLED = new Set(["buffer", "events"]);

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  // Node built-ins stay external (desktop loads them lazily; the phone never asks for them),
  // except the ones isomorphic-git needs at load time, which are bundled from their npm polyfills.
  external: [
    "obsidian",
    "electron",
    ...builtinModules.filter((m) => !POLYFILLED.has(m)),
    ...builtinModules.filter((m) => !POLYFILLED.has(m)).map((m) => `node:${m}`),
  ],
  alias: { "node:buffer": "buffer", "node:events": "events" },
  // isomorphic-git uses the global `Buffer` (76 places). Phones have none, so inject the polyfill.
  inject: ["src/shims/buffer-global.js"],
  format: "cjs",
  target: "es2021",
  // "browser" makes isomorphic-git resolve to its browser build (no Node built-ins at load time),
  // which is what the phone needs. Desktop-only modules (node:fs, isomorphic-git/http/node) stay
  // external and are loaded lazily by src/node-env.ts.
  platform: "browser",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
